import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import vm from 'node:vm';
const context=vm.createContext({window:{},document:{body:{dataset:{root:'.'}},addEventListener(){}},Intl,URLSearchParams});
for(const file of ['data-service.js','search.js'])vm.runInContext(readFileSync('assets/js/'+file,'utf8'),context);
const load=name=>JSON.parse(readFileSync('data/'+name+'.json','utf8').replace(/^\uFEFF/,''));
const pages=load('pages'),documents=load('documents');
pages.push({id:'private-page',title:'PRIVATE_SEARCH_PROBE',visibility:'internal',sections:[]});
pages.push({id:'draft-page',title:'DRAFT_SEARCH_PROBE',status:'draft',sections:[]});
documents.push({id:'private-file',title:'PRIVATE_FILE_PROBE',status:'published',visibility:'internal'});
documents.push({id:'draft-file',title:'DRAFT_FILE_PROBE',status:'draft',visibility:'public'});
const search=context.window.MedSearch;
const index=search.buildIndex(load('site'),load('units'),load('people'),load('news'),pages,documents);
const organization=load('organization');
organization.supervised.push({id:'hidden',label:'PRIVATE_SUPERVISED_PROBE',visibility:'internal',status:'active'});
organization.supervised.push({id:'draft',label:'DRAFT_SUPERVISED_PROBE',visibility:'public',status:'draft'});
const withSupervision=search.buildIndex(load('site'),load('units'),load('people'),load('news'),pages,documents,organization);
assert.ok(search.search(withSupervision,'受試者保護中心').some(n=>n.type==='督導單位'&&n.href.endsWith('page=governance&supervised=human-research-protection')));
for(const probe of ['PRIVATE_SUPERVISED_PROBE','DRAFT_SUPERVISED_PROBE'])assert.equal(search.search(withSupervision,probe).length,0);
assert.ok(search.search(index,'周三芳').some(x=>x.href.includes('research-consultation')));
assert.ok(search.search(index,'論文撰寫').some(x=>x.href.includes('writing')));
assert.ok(search.search(index,'參與者同意書').some(x=>x.type==='文件表單'&&x.href.includes('downloads&q=')));
assert.ok(!documents.some(d=>d.is_demo||d.file?.href?.startsWith('assets/documents/demo/')));
for(const probe of ['PRIVATE_SEARCH_PROBE','DRAFT_SEARCH_PROBE','PRIVATE_FILE_PROBE','DRAFT_FILE_PROBE'])assert.equal(search.search(index,probe).length,0);
const units=load('units'),ai=units.find(u=>u.id==='ai-center'),about=pages.find(p=>p.id==='department-about'),before=JSON.stringify(about);
ai.short_description='SUMMARY_SYNC_PROBE';
const resolved=context.window.MedData.resolveUnitCards(about,units);
assert.ok(resolved.groups.some(g=>g.cards.some(c=>c.title===ai.name&&c.text==='SUMMARY_SYNC_PROBE')));
assert.equal(JSON.stringify(about),before,'Resolving cards must preserve the stored page');
const hidden=context.window.MedData.resolveUnitCards(about,units.map(u=>u.id===ai.id?{...u,visibility:'internal'}:u));
assert.ok(!hidden.groups.some(g=>g.cards.some(c=>c.title===ai.name)),'Private unit cards must be excluded');
const updated=search.buildIndex(load('site'),units,load('people'),load('news'),pages,documents);
assert.ok(search.search(updated,'SUMMARY_SYNC_PROBE').some(x=>x.type==='研究資源'));
console.log('PASS resource search: people/resource pages/documents discoverable, private and draft records excluded');
