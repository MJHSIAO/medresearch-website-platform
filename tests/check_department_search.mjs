import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import vm from 'node:vm';
const context=vm.createContext({window:{},document:{body:{dataset:{root:'.'}},addEventListener(){}},Intl,URLSearchParams,URL,location:{href:'https://site.example/content-page.html?page=department-about'}});
for(const name of ['data-service.js','search.js'])vm.runInContext(readFileSync('assets/js/'+name,'utf8'),context);
const load=name=>JSON.parse(readFileSync('data/'+name+'.json','utf8').replace(/^\uFEFF/,''));
const D=context.window.MedData,units=load('units'),people=load('people'),pages=load('pages');
assert.equal(units.filter(D.publicUnit).length,8,'Parent must not appear as its own child');
const page=pages.find(p=>p.id==='department-about'),before=JSON.stringify(page);
const main=units.find(u=>u.id==='medresearch');main.full_description='MAIN_INTRO_SYNC';
const resolved=D.resolveUnitCards(page,units,people);
assert.equal(resolved.groups[0].text,'MAIN_INTRO_SYNC');
assert.equal(JSON.stringify(page),before);
const leaders=resolved.groups.find(g=>g.title==='組織與主管'),members=resolved.groups.find(g=>g.id==='department-members');
assert.equal(leaders.cards.filter(c=>c.title==='吳彥雯').length,1);
assert.equal(members.cards.length,7);
const person=people.find(p=>p.id==='person-medresearch-lee');person.visibility='internal';
const hidden=D.resolveUnitCards(page,units,people);
assert.ok(!hidden.groups.flatMap(g=>g.cards).some(c=>c.title===person.name));
person.visibility='public';person.name='姓名同步測試';person.title='更新職稱';person.display_order=-1;
assert.equal(D.resolveUnitCards(page,units,people).groups.find(g=>g.id==='department-members').cards[0].title,'姓名同步測試');
const index=context.window.MedSearch.buildIndex(load('site'),units,people,load('news'),pages,load('documents'));
assert.ok(context.window.MedSearch.search(index,'姓名同步測試').some(e=>e.type==='成員'&&e.href.endsWith('#department-members')));
assert.ok(!index.some(e=>e.type==='單位'&&e.title==='醫學研究部'));
vm.runInContext(readFileSync('assets/js/resource-directory.js','utf8'),context);
const target={classList:{add(){}},innerHTML:''};
context.window.MedResourceDirectory.render(target,resolved);
assert.doesNotMatch(target.innerHTML,/原官網|原站|資料來源與使用提醒|主管資料與本部成員共用/);
assert.match(target.innerHTML,/查看公開介紹/);
assert.ok(people.filter(p=>p.unit_id==='medresearch').every(p=>p.source_url&&p.source_updated_at==='2026-05-04'));
context.window.MedResourceDirectory.render(target,pages.find(p=>p.id==='research-services'));
assert.match(target.innerHTML,/resource-source/,'Other resource pages retain their source section');
main.visibility='internal';
assert.equal(D.resolveUnitCards(page,units,people).groups.length,0);
assert.ok(!context.window.MedSearch.buildIndex(load('site'),units,people,[],pages,[]).some(e=>e.type==='成員'&&e.title==='姓名同步測試'));
console.log('PASS parent/child separation, shared leadership/member snapshots, intro sync, ordering, search and internal exclusion');
